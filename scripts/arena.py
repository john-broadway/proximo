#!/usr/bin/env python3
"""The arena inventory: every published address, by the verdict the engine gives it, armed.

GENERATED, NEVER HAND-EDITED (`python scripts/arena.py > docs/arena.md`; tests/test_arena.py
refuses a stale copy). John, 2026-10-04: "equip the fighter for the arena, allow them to enter
the arena from any gate offered." A reviewer reads this table, never a claim about it: the
classes are the engine's own (`govern()`'s order), the counts are the table's, and the held and
gated rows carry their sentences so what the door refuses on purpose is read, not inferred.
"""
from __future__ import annotations

import pathlib
import sys
from collections import Counter

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "src"))

from proximo.core import engine  # noqa: E402

PLANES = ("pve", "pbs", "pmg", "pdm")
CLASSES = (
    ("read", "reads served"),
    ("open", "mutations open to an armed operator (tiered)"),
    ("opt-in", "opened by an operator switch, judged like any mutation (guest agent, container and node shell)"),
    ("download", "the download lane: bytes land on this host under a cap once PROXIMO_ENABLE_DOWNLOAD is on"),
    ("held", "mutations refused on purpose, with a sentence (`needs=held`)"),
    ("stream", "hard-gated, served by nothing"),
    ("tunnel", "excluded: not a JSON call (protocol upgrades, console tickets, a deprecated alias)"),
)


def classify(row: engine.Row) -> str:
    if row.excluded:
        return "tunnel"
    lane = engine.opt_in_lane(row) if row.gate else None
    if row.gate and lane is None:
        return "stream"
    if lane == "download":
        return "download"
    if row.access == engine.READ:
        return "opt-in" if row.gate else "read"     # an agent read is served only once opted in
    if row.held:
        return "held"
    judged = isinstance(row.tier, str) and row.tier in engine.TIERS
    if row.gate:         # an opt-in lane: judged like any mutation once the operator opts in
        return "opt-in" if judged else "SILENT"
    if judged:
        return "open"
    return "SILENT"      # a published mutation with no verdict: tests/test_arena.py is red


def tunnel_kind(row: engine.Row) -> str:
    tail = row.path.rsplit("/", 1)[-1]
    if row.path.startswith("/config/whitelist"):
        return "deprecated alias (pmg `/config/whitelist` = `/config/welcomelist`, which is served)"
    if tail in ("termproxy", "vncproxy", "spiceproxy", "vncshell", "spiceshell"):
        return "console ticket (a POST that mints the credential for an interactive console)"
    return "protocol upgrade (websocket, backup and reader protocols, migration tunnels)"


def render() -> str:
    rows = list(engine.table().values())
    by = Counter(classify(r) for r in rows)
    per = {p: Counter(classify(r) for r in rows if r.product == p) for p in PLANES}
    out = ["# The arena", "",
           "Every address the four Proxmox products publish, by the verdict the engine gives it to an",
           "armed operator. Generated by `scripts/arena.py`; `tests/test_arena.py` refuses a stale copy",
           "and refuses a published mutation with no verdict at all.", "",
           "| class | total | " + " | ".join(PLANES) + " |", "|---|---|" + "---|" * len(PLANES)]
    for key, label in CLASSES:
        out.append(f"| {label} | {by[key]} | " + " | ".join(str(per[p][key]) for p in PLANES) + " |")
    totals = " | ".join(str(sum(per[p].values())) for p in PLANES)
    out.append(f"| **every published address** | **{len(rows)}** | {totals} |")
    if by["SILENT"]:
        out += ["", f"**{by['SILENT']} published mutation(s) have NO verdict** (the guard is red):",
                *(f"- `{r.key}`" for r in rows if classify(r) == "SILENT")]
    out += ["", "## Held: refused on purpose", "",
            "A held line is a judgement with a sentence, read by `govern()` before arm. Opening one is a",
            "line moved from `[tier.held]` to `[tier]` in `tiers.toml`, John's hand by name.", ""]
    for r in sorted((r for r in rows if classify(r) == "held"), key=lambda r: r.key):
        out.append(f"- `{r.key}`: {r.held.split(' [Claude')[0]}")
    out += ["", "## The download lane", "",
            "A byte stream, not JSON: the bytes land under `PROXIMO_RESTORE_DIR` in a fresh private directory,",
            "capped by `PROXIMO_RESTORE_MAX_BYTES`, and the answer carries the path, the count and the sha256.",
            "Opt-in: `PROXIMO_ENABLE_DOWNLOAD=1`. The raw GET door still refuses them (it answers JSON).", ""]
    for r in sorted((r for r in rows if classify(r) == "download"), key=lambda r: r.key):
        out.append(f"- `{r.key}`" + (" (untrusted bytes)" if r.untrusted else ""))
    if any(classify(r) == "stream" for r in rows):
        out += ["", "## Hard-gated, served by nothing", ""]
        hard = sorted((r for r in rows if classify(r) == "stream"), key=lambda r: r.key)
        out += [f"- `{r.key}`: {r.gate}" for r in hard]
    kinds = Counter(tunnel_kind(r) for r in rows if classify(r) == "tunnel")
    out += ["", "## Excluded: not a JSON call", ""]
    for kind, n in sorted(kinds.items(), key=lambda kv: -kv[1]):
        out.append(f"- {n}: {kind}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.stdout.write(render())
